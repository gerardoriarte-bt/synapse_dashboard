-- ==========================================================================================
-- DEFINICION SQL: MODELO / METRICA MEDIA_BY_CAMPAIGN (TERPEL)
-- Grano: PERIODO + CAMPANA (Macro Estratégico)
-- Fuente: DB_BT_TERPEL_COMBS.BT_TERPEL_COMBS_MART_ANALYTICS.VW_DATATERPEL_PAUTA_ENTREGA_SYNAPSE
-- Fecha: 2026-11-09
-- ==========================================================================================

CREATE OR REPLACE VIEW DB_BT_TERPEL_COMBS.BT_TERPEL_COMBS_MART_ANALYTICS.VW_SYNAPSE_MEDIA_BY_CAMPAIGN AS
SELECT
    PERIODO,
    CAMPANA,
    FAMILIA_NORM,
    CUENTA_NORM,
    
    -- Fechas agregadas de vigencia de campaña
    MIN(FECHA_INICIO) AS FECHA_INICIO_CAMPANA,
    MAX(FECHA_FIN) AS FECHA_FIN_CAMPANA,
    
    -- Inversión y Ejecución Financiera
    SUM(PRESUPUESTO) AS PRESUPUESTO_TOTAL,
    SUM(GASTO_FINAL) AS GASTO_TOTAL,
    DIV0NULL(SUM(GASTO_FINAL), SUM(PRESUPUESTO)) AS PCT_EJECUCION_PRESUPUESTO,
    
    -- Metas y Resultados de Medios (Aditivos)
    SUM(META_IMPRESIONES) AS TOTAL_META_IMPRESIONES,
    SUM(RESULTADO_IMPRESIONES) AS TOTAL_RESULTADO_IMPRESIONES,
    DIV0NULL(SUM(RESULTADO_IMPRESIONES), SUM(META_IMPRESIONES)) AS PCT_CUMPLIMIENTO_IMPRESIONES,
    
    SUM(META_CLICS) AS TOTAL_META_CLICS,
    SUM(RESULTADO_CLICS) AS TOTAL_RESULTADO_CLICS,
    DIV0NULL(SUM(RESULTADO_CLICS), SUM(META_CLICS)) AS PCT_CUMPLIMIENTO_CLICS,
    
    SUM(META_ALCANCE) AS TOTAL_META_ALCANCE,
    SUM(RESULTADO_ALCANCE) AS TOTAL_RESULTADO_ALCANCE,
    DIV0NULL(SUM(RESULTADO_ALCANCE), SUM(META_ALCANCE)) AS PCT_CUMPLIMIENTO_ALCANCE,
    
    SUM(META_VIEWS) AS TOTAL_META_VIEWS,
    SUM(RESULTADO_VIEWS) AS TOTAL_RESULTADO_VIEWS,
    DIV0NULL(SUM(RESULTADO_VIEWS), SUM(META_VIEWS)) AS PCT_CUMPLIMIENTO_VIEWS,
    
    SUM(META_LEADS) AS TOTAL_META_LEADS,
    SUM(RESULTADO_LEADS) AS TOTAL_RESULTADO_LEADS,
    DIV0NULL(SUM(RESULTADO_LEADS), SUM(META_LEADS)) AS PCT_CUMPLIMIENTO_LEADS,
    
    SUM(META_INTERACCIONES) AS TOTAL_META_INTERACCIONES,
    SUM(RESULTADO_INTERACCIONES) AS TOTAL_RESULTADO_INTERACCIONES,
    DIV0NULL(SUM(RESULTADO_INTERACCIONES), SUM(META_INTERACCIONES)) AS PCT_CUMPLIMIENTO_INTERACCIONES,
    
    SUM(META_DESCARGAS) AS TOTAL_META_DESCARGAS,
    SUM(RESULTADO_DESCARGAS) AS TOTAL_RESULTADO_DESCARGAS,
    DIV0NULL(SUM(RESULTADO_DESCARGAS), SUM(META_DESCARGAS)) AS PCT_CUMPLIMIENTO_DESCARGAS,
    
    SUM(META_ESCUCHAS) AS TOTAL_META_ESCUCHAS,
    SUM(RESULTADO_ESCUCHAS) AS TOTAL_RESULTADO_ESCUCHAS,
    DIV0NULL(SUM(RESULTADO_ESCUCHAS), SUM(META_ESCUCHAS)) AS PCT_CUMPLIMIENTO_ESCUCHAS,
    
    -- Eficiencias Ponderadas
    DIV0NULL(SUM(RESULTADO_CLICS), SUM(RESULTADO_IMPRESIONES)) AS CTR_PONDERADO,
    DIV0NULL(SUM(RESULTADO_VIEWS), SUM(RESULTADO_IMPRESIONES)) AS VTR_PONDERADO,
    DIV0NULL(SUM(GASTO_FINAL), SUM(RESULTADO_CLICS)) AS CPC_REAL,
    DIV0NULL(SUM(GASTO_FINAL), (SUM(RESULTADO_IMPRESIONES) / 1000.0)) AS CPM_REAL,
    
    -- Cantidad de líneas tácticas que componen la campaña
    COUNT(DISTINCT NOMBRE_CAMPANA) AS TOTAL_LINEAS_PAUTA,
    COUNT(*) AS TOTAL_REGISTROS_PAUTA

FROM DB_BT_TERPEL_COMBS.BT_TERPEL_COMBS_MART_ANALYTICS.VW_DATATERPEL_PAUTA_ENTREGA_SYNAPSE
GROUP BY
    PERIODO,
    CAMPANA,
    FAMILIA_NORM,
    CUENTA_NORM;
